from datetime import datetime
from typing import Annotated, Any, Literal
from uuid import UUID

from pydantic import Field, SecretStr, StringConstraints

from sallimbook.identity.passkeys.models import StepUpPurpose
from sallimbook.identity.schemas import DisplayName, InputModel, InstallClaim, LoginName

Base64UrlId = Annotated[
    str, StringConstraints(min_length=1, max_length=1364, pattern=r"^[A-Za-z0-9_-]+$")
]
TransportName = Literal["usb", "nfc", "ble", "smart-card", "internal", "cable", "hybrid"]


class CredentialProperties(InputModel):
    rk: bool


class ClientExtensions(InputModel):
    # No PRF output, keys, or arbitrary extension material is accepted by this auth API.
    credProps: CredentialProperties | None = None


class RegistrationAttestation(InputModel):
    clientDataJSON: str = Field(min_length=1, max_length=8192, repr=False)
    attestationObject: str = Field(min_length=1, max_length=65536, repr=False)
    transports: list[TransportName] = Field(default_factory=list, max_length=7)
    # Modern browser toJSON() may include these redundant public fields. Verification uses
    # the attestation object rather than trusting the extra copies.
    authenticatorData: str | None = Field(default=None, max_length=4096, repr=False)
    publicKey: str | None = Field(default=None, max_length=8192, repr=False)
    publicKeyAlgorithm: int | None = None


class RegistrationCredential(InputModel):
    id: Base64UrlId
    rawId: Base64UrlId
    type: Literal["public-key"]
    response: RegistrationAttestation
    authenticatorAttachment: Literal["platform", "cross-platform"] | None = None
    clientExtensionResults: ClientExtensions = Field(default_factory=ClientExtensions)


class AssertionResponse(InputModel):
    clientDataJSON: str = Field(min_length=1, max_length=8192, repr=False)
    authenticatorData: str = Field(min_length=1, max_length=4096, repr=False)
    signature: str = Field(min_length=1, max_length=2048, repr=False)
    userHandle: str | None = Field(default=None, max_length=128, repr=False)


class AuthenticationCredential(InputModel):
    id: Base64UrlId
    rawId: Base64UrlId
    type: Literal["public-key"]
    response: AssertionResponse
    authenticatorAttachment: Literal["platform", "cross-platform"] | None = None
    clientExtensionResults: ClientExtensions = Field(default_factory=ClientExtensions)


class RegisterOptionsRequest(InputModel):
    label: DisplayName


class RegisterVerification(InputModel):
    challenge_id: UUID
    credential: RegistrationCredential


class LoginOptionsRequest(InputModel):
    login_name: LoginName
    device_label: DisplayName


class AssertionVerification(InputModel):
    challenge_id: UUID
    credential: AuthenticationCredential


class NativeLoginVerification(AssertionVerification):
    device_binding: SecretStr = Field(min_length=32, max_length=128)
    # Opt-in, so an older app that never sends it keeps the old response.
    install: InstallClaim | None = None


class StepUpOptionsRequest(InputModel):
    purpose: StepUpPurpose
    target_id: UUID


class OptionsResponse(InputModel):
    challenge_id: UUID
    # Generated by py_webauthn's standard JSON serializer, not a second handwritten contract.
    public_key: dict[str, Any]
    expires_at: datetime


class NativeOptionsResponse(OptionsResponse):
    device_binding: str = Field(repr=False)


class CredentialResponse(InputModel):
    id: UUID
    label: str
    created_at: datetime
    last_used_at: datetime | None
    backed_up: bool
    device_type: Literal["single_device", "multi_device"]
    version: int


class CredentialListResponse(InputModel):
    items: list[CredentialResponse]
    next_cursor: UUID | None


class StepUpResponse(InputModel):
    grant_token: str = Field(repr=False)
    purpose: StepUpPurpose
    target_id: UUID
    expires_at: datetime

const labels: Record<string, string> = {};
for (const [label, names] of groups) for (const name of names) labels[name] = label;

/** The Korean label for one audit field name; a name the table does not know is "기타 항목". */
export const fieldLabel = (name: string): string =>
  Object.hasOwn(labels, name) ? labels[name]! : "기타 항목";

/** Labels for a record's changed fields, each shown once, in the order first seen. */
export const changedFieldLabels = (names: string[]): string[] => [
  ...new Set(names.map(fieldLabel)),
];

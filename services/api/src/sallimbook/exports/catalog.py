def validate_catalog(metadata):
    known = set(PUBLIC_COLUMNS) | set(PRIVATE_TABLES) | set(SPECIAL_COLUMNS)
    if known != set(metadata.tables):
        raise ValueError("Export table classification must be reviewed")
    for name, table in metadata.tables.items():
        if name in PUBLIC_COLUMNS:
            columns = (*PUBLIC_COLUMNS[name], *PRIVATE_COLUMNS.get(name, ()))
        elif name in PRIVATE_TABLES:
            columns = PRIVATE_TABLES[name]
        else:
            columns = (*SPECIAL_COLUMNS[name]["public"], *SPECIAL_COLUMNS[name]["private"])
        if len(columns) != len(set(columns)) or set(columns) != set(table.columns.keys()):
            raise ValueError("Export column classification must be reviewed")
